let currentLang = localStorage.getItem('pakspeed_lang') || 'ur';

// Expose on window so other scripts can access via window.translations / window.currentLang
window.translations = translations;
window.currentLang = currentLang;

function applyLanguage(lang) {
  currentLang = lang;
  window.currentLang = lang;
  document.documentElement.lang = lang;
  document.documentElement.dir = lang === 'ur' ? 'rtl' : 'ltr';
  document.body.className = lang === 'ur' ? 'lang-ur' : 'lang-en';
  localStorage.setItem('pakspeed_lang', lang);

  const strings = translations[lang];

  // Update data-i18n elements
  document.querySelectorAll('[data-i18n]').forEach(el => {
    const key = el.getAttribute('data-i18n');
    if (strings[key]) el.innerHTML = strings[key];
  });

  // Update data-i18n-placeholder elements
  document.querySelectorAll('[data-i18n-placeholder]').forEach(el => {
    const key = el.getAttribute('data-i18n-placeholder');
    if (strings[key]) el.placeholder = strings[key];
  });

  // Toggle button text
  const toggleBtn = document.getElementById('btn-lang');
  if (toggleBtn && strings['toggle.btn']) {
    toggleBtn.innerText = strings['toggle.btn'];
  }

  // Refresh quality badges and feedback in the new language
  if (typeof window.refreshQualityBadges === 'function') {
    window.refreshQualityBadges();
  }

  // Refresh community counter in new language
  if (typeof window.refreshCounter === 'function') {
    window.refreshCounter();
  }

  // Refresh ISP display in the header
  const ispEl = document.getElementById('isp-display');
  if (ispEl && window.pakspeedData && window.pakspeedData.isp !== 'Unknown') {
    const ispData = typeof getISPData === 'function' ? getISPData() : null;
    if (ispData) {
      const cityName = ispData.city ? ` — ${ispData.city}` : '';
      const ispStr = lang === 'ur' ? ispData.urdu : ispData.name;
      ispEl.innerText = `${ispStr}${cityName}`;
    }
  }
}

document.addEventListener('DOMContentLoaded', () => {
  applyLanguage(currentLang);

  const toggleBtn = document.getElementById('btn-lang');
  if (toggleBtn) {
    toggleBtn.addEventListener('click', () => {
      applyLanguage(currentLang === 'ur' ? 'en' : 'ur');
    });
  }
});
